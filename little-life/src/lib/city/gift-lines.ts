/** 이 사람이 이 결과에 할 말들 */
export function giftLines(npcId: NpcId, preference: GiftPreference): string[] {
  return LINES[npcId][preference]
}

/**
 * 한 줄 고른다.
 *
 * 부엌에서 만든 음식에는 그 사람과 그 음식에만 붙은 말이 따로 있다
 * (`kitchen/gifts.ts`). 그게 있으면 그쪽이 먼저다 — 여기 있는 건
 * 아무 물건에나 쓰는 일반적인 대답이라, 더 구체적인 말을 덮으면 손해다.
 */
export function pickGiftLine(
  npcId: NpcId,
  preference: GiftPreference,
  specific: string[],
  random: () => number = Math.random,
): string {
  const pool = specific.length > 0 ? specific : giftLines(npcId, preference)
  return pool[Math.floor(random() * pool.length)] ?? pool[0]
}
